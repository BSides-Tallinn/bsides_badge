_frames = {}


def _face_frame(index):
    import framebuf
    if index not in _frames:
        _frames[index] = framebuf.FrameBuffer(
            FACES[index], 48, 50, framebuf.MONO_HLSB)
    return _frames[index]


def draw_oled(oled, level):
    """Draw the title and selected monochrome expression."""
    level = normalize_level(level)
    oled.fill(0)
    oled.text("My Social", 0, 21, 1)
    oled.text("Battery", 8, 35, 1)
    oled.blit(_face_frame(level - 1), 77, 7)
    oled.show()
