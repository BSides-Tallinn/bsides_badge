"""Five-level social battery state and monochrome OLED rendering.

The LED indices follow the NeoPixel wiring order. The physical position of
index zero must be checked on hardware before claiming clockwise filling.
"""

class SocialBatteryLevel:
    PERSEVERING = 1
    DRAINED = 2
    NEUTRAL = 3
    HAPPY = 4
    ENERGIZED = 5


MIN_LEVEL = SocialBatteryLevel.PERSEVERING
MAX_LEVEL = SocialBatteryLevel.ENERGIZED
DEFAULT_LEVEL = SocialBatteryLevel.NEUTRAL
LED_COUNTS = (4, 7, 10, 13, 16)
COLORS = ((255, 0, 0), (255, 90, 0), (255, 200, 0),
          (120, 220, 0), (0, 255, 0))


def valid_level(value):
    return type(value) is int and MIN_LEVEL <= value <= MAX_LEVEL


def normalize_level(value):
    return value if valid_level(value) else DEFAULT_LEVEL


def gauge_pixels(level, count=16, brightness=10):
    """Return a static, contiguous LED gauge in hardware index order."""
    level = normalize_level(level)
    brightness = max(0, min(100, int(brightness)))
    lit = (LED_COUNTS[level - 1] * count + LED_COUNTS[-1] // 2) // LED_COUNTS[-1]
    color = tuple(channel * brightness // 100 for channel in COLORS[level - 1])
    return [color if index < lit else (0, 0, 0)
            for index in range(count)]


